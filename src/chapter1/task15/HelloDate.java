package chapter1.task15;

import java.util.*;

/**
 * Класс {@code HelloDate} демонстрирует базовый вывод текущей даты и времени.
 * <p>
 * Этот класс является простым примером программы на Java, которая выводит
 * приветствие и текущую системную дату с использованием класса {@link Date}.
 * </p>
 *
 * @author Иванов Иван Иванович
 * @version 1.0
 * @see java.util.Date
 * @since 1.0
 */
public class HelloDate {

    /**
     * Точка входа в программу.
     * <p>
     * Метод выводит в стандартный поток вывода приветствие "{@code Привет, сегодня: }",
     * а затем текущую дату и время, полученные с помощью конструктора {@link Date#Date()}.
     * </p>
     *
     * @param args аргументы командной строки (не используются в данной реализации)
     */
    public static void main(String[] args) {
        // Вывод приветствия
        System.out.println("Привет, сегодня: ");

        // Создание объекта Date и вывод текущей даты и времени
        System.out.println(new Date());
    }

}

